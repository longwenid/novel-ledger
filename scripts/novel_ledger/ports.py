"""Explicit boundaries between use cases and replaceable adapters.

Ports never discover paths, connections, processes or the caller's environment.
Optional file transport is explicit data, rather than a requirement on every delivery.
Readers receive narrow capabilities; application transactions use the full repository.
"""
from __future__ import annotations

from typing import Any, Callable, Dict, Protocol, TypedDict
from .contracts import Job


class DocumentReader(Protocol):
    def read_document(self, key): ...


class VerificationReader(DocumentReader, Protocol):
    """Immutable source verification has no save, transaction or task mutation capability."""
    def headers(self, branch): ...


class VerificationSources:
    """A concrete capability view; do not hand a verifier the mutable repository."""
    __slots__ = ('read_document', 'headers')

    def __init__(self, read_document, headers):
        self.read_document = read_document
        self.headers = headers


class PublicationReader(DocumentReader, Protocol):
    def load(self): ...
    def headers(self, branch): ...
    def get(self, key, default=None): ...


class ContextStore(DocumentReader, Protocol):
    """Frozen source assembly, without task lifecycle or filesystem access."""
    def document(self, value): ...
    def headers(self, branch): ...
    def chapter(self, branch, chapter): ...
    def history_snapshot(self, branch): ...


class Repository(PublicationReader, ContextStore, Protocol):
    """Transactional application persistence; concrete construction is external."""
    def close(self): ...
    def transaction(self, preview=False): ...
    def after_commit(self, callback: Callable[[], None]): ...
    def put(self, key, value): ...
    def load_part(self, name): ...
    def save(self, book): ...
    def pending(self): ...
    def task_rows(self): ...
    def task(self, task_id): ...
    def add_task(self, work): ...
    def finish_task(self, task_id, result): ...
    def cancel_pending(self, reason): ...
    def history_pages(self, snapshot, before=None): ...
    def memory_rows(self, page): ...
    def add_chapter(self, branch, row): ...
    def fork(self, parent, first): ...
    def promote(self, branch, parent): ...
    def session_task(self, session): ...
    def bind_session(self, session, task_id): ...
    def usage(self): ...
    def read_names(self, task_id): ...
    def record(self, action, value): ...
    def prune(self): ...


class FileTaskTransport(TypedDict):
    """Optional file transport required specifically by the local process host."""
    project_path: str
    task_path: str
    log_path: str


class TaskIdentity(TypedDict):
    task_id: str


class TaskDelivery(TaskIdentity, total=False):
    task_path: str
    process: FileTaskTransport


class TaskStatus(TypedDict):
    id: str
    status: str
    reviewer: Any


class WorkerLease(TypedDict):
    token: str


class Presentation(Protocol):
    """Task and publication delivery, independent of storage representation."""
    def task(self, task, baseline=None, compact=False) -> TaskDelivery: ...
    def revision_path(self, plan_hash): ...
    def revision(self, plan): ...
    def world(self): ...
    def book(self): ...
    def board(self, board): ...
    def retire(self, task_id): ...


class HostApplication(Protocol):
    """Public use cases required by a process host; no repository access."""
    def advance(self, after=None, owner=None, compact=False, wait_pending=False): ...
    def claim(self, task_id, session, seconds=300) -> WorkerLease: ...
    def release_claim(self, task_id, token): ...
    def renew(self, owner, seconds=300): ...
    def task_status(self, task_id) -> TaskStatus: ...


class WatchApplication(Protocol):
    """The subset an unattended wait loop needs: advance, watch a task, keep the lease alive."""
    def advance(self, after=None, owner=None, compact=False, wait_pending=False): ...
    def renew(self, owner, seconds=300): ...
    def task_status(self, task_id) -> TaskStatus: ...


TaskCompiler = Callable[[Dict[str, Any], Job], Dict[str, Any]]
